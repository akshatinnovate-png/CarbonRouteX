/**
 * MOCK MAP, ROUTING AND ADDRESS SERVICES
 *
 * Stands in for the Esri tile servers, OSRM and Nominatim so the browser
 * walkthrough exercises the real network code paths — the same fetches, the
 * same parsing, the same fallbacks — without depending on a live public
 * service that is rate-limited and occasionally down.
 *
 * It deliberately behaves like the *stingy* public OSRM: the `alternatives`
 * request returns exactly one road, and only a via-point request produces a
 * different corridor. That is the case the application has to handle well, so
 * it is the case the test pins.
 *
 *   node tests/mock-services.mjs      # serves on http://localhost:8899
 */
import http from 'node:http';
import zlib from 'node:zlib';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);

const PORT = 8899;
const cors = { 'Access-Control-Allow-Origin': '*' };

// A 256x256 PNG generated by hand: solid colour with a grid. Built once.
function tilePng(z, x, y) {
  // Minimal uncompressed-ish PNG via zlib
  const W = 256, H = 256;
  const px = Buffer.alloc(W * H * 3);
  const shade = ((x + y) % 2) ? 0x1c : 0x22;
  for (let i = 0; i < W * H; i++) {
    const cx = i % W, cy = (i / W) | 0;
    const line = (cx % 64 === 0 || cy % 64 === 0);
    px[i*3] = line ? 0x3a : shade;
    px[i*3+1] = line ? 0x4a : shade + 6;
    px[i*3+2] = line ? 0x60 : shade + 14;
  }
  const raw = Buffer.alloc((W * 3 + 1) * H);
  for (let r = 0; r < H; r++) {
    raw[r * (W*3+1)] = 0;
    px.copy(raw, r*(W*3+1)+1, r*W*3, (r+1)*W*3);
  }
  const idat = zlib.deflateSync(raw);
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td) >>> 0);
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4);
  ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([
    Buffer.from([0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a]),
    chunk('IHDR', ihdr), chunk('IDAT', idat), chunk('IEND', Buffer.alloc(0)),
  ]);
}
let TABLE = null;
function crc32(buf) {
  if (!TABLE) {
    TABLE = new Int32Array(256);
    for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; TABLE[n] = c; }
  }
  let c = -1;
  for (let i = 0; i < buf.length; i++) c = TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
}

const hav = (aLon,aLat,bLon,bLat) => {
  const R=6371.0088, t=Math.PI/180;
  const dLat=(bLat-aLat)*t, dLon=(bLon-aLon)*t;
  const s=Math.sin(dLat/2)**2+Math.cos(aLat*t)*Math.cos(bLat*t)*Math.sin(dLon/2)**2;
  return 2*R*Math.asin(Math.min(1,Math.sqrt(s)));
};

function encodePolyline(points, precision = 6) {
  const factor = 10 ** precision;
  let out = '', prevLat = 0, prevLon = 0;
  const enc = (v) => {
    v = v < 0 ? ~(v << 1) : (v << 1);
    let s = '';
    while (v >= 0x20) { s += String.fromCharCode((0x20 | (v & 0x1f)) + 63); v >>= 5; }
    return s + String.fromCharCode(v + 63);
  };
  for (const p of points) {
    const lat = Math.round(p.lat * factor), lon = Math.round(p.lon * factor);
    out += enc(lat - prevLat) + enc(lon - prevLon);
    prevLat = lat; prevLon = lon;
  }
  return out;
}

http.createServer((req, res) => {
  const url = new URL(req.url, 'http://x');
  if (req.method === 'OPTIONS') { res.writeHead(204, cors); return res.end(); }

  let m = url.pathname.match(/^\/tiles\/(\d+)\/(\d+)\/(\d+)\.png$/);
  if (m) {
    const png = tilePng(+m[1], +m[2], +m[3]);
    res.writeHead(200, { ...cors, 'Content-Type': 'image/png' });
    return res.end(png);
  }

  // Esri-style tile path: /.../MapServer/tile/{z}/{y}/{x}
  m = url.pathname.match(/\/tile\/(\d+)\/(\d+)\/(\d+)$/);
  if (m) {
    const png = tilePng(+m[1], +m[3], +m[2]);
    res.writeHead(200, { ...cors, 'Content-Type': 'image/png' });
    return res.end(png);
  }

  m = url.pathname.match(/^\/table\/v1\/\w+\/(.+)$/);
  if (m) {
    const pts = m[1].split(';').map((c) => { const [lon, lat] = c.split(',').map(Number); return { lon, lat }; });
    const n = pts.length;
    const durations = [], distances = [];
    for (let i = 0; i < n; i++) {
      durations.push([]); distances.push([]);
      for (let j = 0; j < n; j++) {
        const km = i === j ? 0 : hav(pts[i].lon, pts[i].lat, pts[j].lon, pts[j].lat) * 1.35;
        distances[i].push(km * 1000);
        durations[i].push((km / 28) * 3600);
      }
    }
    res.writeHead(200, { ...cors, 'Content-Type': 'application/json' });
    return res.end(JSON.stringify({ code: 'Ok', durations, distances }));
  }

  m = url.pathname.match(/^\/route\/v1\/\w+\/(.+)$/);
  if (m) {
    const pts = m[1].split(';').map((c) => { const [lon, lat] = c.split(',').map(Number); return { lon, lat }; });
    // Fake "road" geometry: dog-leg through an intermediate point per leg.
    const geom = [];
    let distance = 0;
    for (let i = 0; i < pts.length; i++) {
      if (i > 0) {
        const a = pts[i-1], b = pts[i];
        geom.push({ lon: b.lon, lat: a.lat });
        distance += (Math.abs(b.lon-a.lon)*111*Math.cos(a.lat*Math.PI/180) + Math.abs(b.lat-a.lat)*111) * 1000;
      }
      geom.push(pts[i]);
    }
    // Named steps, the way OSRM reports them: one highway arrives as many
    // fragments, so the app has to sum distance per name to describe a route.
    const ROADS = ['NH-33', 'Ranchi Ring Road', 'NH-114A', 'Old Coastal Road', 'SH-9', 'Grand Trunk Road'];
    const pick = Math.abs(Math.round((pts[1]?.lon ?? 0) * 1000)) % ROADS.length;
    const mid = geom[Math.floor(geom.length / 2)] || pts[0];
    const steps = [
      { name: ROADS[pick], distance: distance * 0.34, duration: 300,
        maneuver: { type: 'depart', location: [pts[0].lon, pts[0].lat] } },
      { name: ROADS[pick], distance: distance * 0.24, duration: 220,
        maneuver: { type: 'continue', location: [mid.lon, mid.lat] } },
      { name: ROADS[(pick + 2) % ROADS.length], distance: distance * 0.27, duration: 260,
        maneuver: { type: 'turn', modifier: 'left', location: [mid.lon, mid.lat] } },
      { name: '', distance: distance * 0.10, duration: 90,
        maneuver: { type: 'roundabout', exit: 2, location: [mid.lon, mid.lat] } },
      { name: 'Service Road', distance: distance * 0.05, duration: 60,
        maneuver: { type: 'turn', modifier: 'right', location: [mid.lon, mid.lat] } },
      { name: '', distance: 0, duration: 0,
        maneuver: { type: 'arrive', location: [pts[pts.length - 1].lon, pts[pts.length - 1].lat] } },
    ];
    const base = {
      geometry: encodePolyline(geom, 6),
      distance,
      duration: distance / 1000 / 28 * 3600,
      legs: [{ steps }],
    };
    // Behave like the real public OSRM: the `alternatives` request yields ONE
    // road. Only a via point (a 3-coordinate request) produces a different
    // corridor, which is exactly the path the app has to exercise.
    const routes = [base];
    if (pts.length > 2) {
      const via = pts[1];
      const shifted = geom.map((g) => ({ lon: g.lon + (via.lon - pts[0].lon) * 0.35, lat: g.lat + (via.lat - pts[0].lat) * 0.35 }));
      const spread = Math.abs(via.lon - pts[0].lon) + Math.abs(via.lat - pts[0].lat);
      routes[0] = {
        geometry: encodePolyline(shifted, 6),
        distance: distance * (1 + spread * 1.4),
        duration: base.duration * (1 + spread * 0.9),
        legs: [{ steps }],
      };
    }
    res.writeHead(200, { ...cors, 'Content-Type': 'application/json' });
    return res.end(JSON.stringify({ code: 'Ok', routes }));
  }

  if (url.pathname === '/search') {
    const q = url.searchParams.get('q') || '';
    // Vary by query so two different searches land in two different places,
    // the way a real geocoder would.
    let h = 0;
    for (const c of q) h = (h * 31 + c.charCodeAt(0)) % 997;
    const base = { lon: 78.4867 + ((h % 37) - 18) * 0.004, lat: 17.385 + ((h % 29) - 14) * 0.004 };
    const out = Array.from({ length: 4 }, (_, i) => ({
      display_name: `${q} result ${i + 1}, Hyderabad, Telangana, India`,
      name: `${q} ${i + 1}`,
      lon: String(base.lon + (i - 1.5) * 0.02),
      lat: String(base.lat + (i - 1.5) * 0.018),
      type: 'building',
      address: { road: `${q} Road`, suburb: 'Banjara Hills', city: 'Hyderabad' },
    }));
    res.writeHead(200, { ...cors, 'Content-Type': 'application/json' });
    return res.end(JSON.stringify(out));
  }

  if (url.pathname === '/reverse') {
    res.writeHead(200, { ...cors, 'Content-Type': 'application/json' });
    return res.end(JSON.stringify({
      display_name: 'Pinned location, Hyderabad, India',
      address: { road: 'Pinned Road', suburb: 'Jubilee Hills', city: 'Hyderabad' },
    }));
  }

  res.writeHead(404, cors); res.end('nope');
}).listen(PORT, () => console.log('mock on', PORT));
